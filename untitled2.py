class AdvancedPhishingDetector:
    def __init__(self):
        # Multiple models for robust ensemble
        self.rf_model = RandomForestClassifier(
            n_estimators=200, max_depth=20, min_samples_split=2,
            min_samples_leaf=1, max_features=0.8, random_state=42,
            class_weight={0: 1, 1: 1.5}, bootstrap=True
        )
        self.xgb_model = xgb.XGBClassifier(
            n_estimators=200, max_depth=8, learning_rate=0.1,
            subsample=0.9, colsample_bytree=0.9, random_state=42,
            scale_pos_weight=2, eval_metric='logloss'
        )
        self.lgb_model = lgb.LGBMClassifier(
            n_estimators=200, max_depth=7, learning_rate=0.1,
            subsample=0.9, colsample_bytree=0.9, random_state=42,
            scale_pos_weight=2, verbosity=-1
        )
        self.gb_model = GradientBoostingClassifier(
            n_estimators=200, max_depth=6, learning_rate=0.1,
            subsample=0.9, random_state=42
        )
        self.scaler = StandardScaler()
        self.is_trained = False

    def fit(self, X_train, y_train, X_val, y_val):
        print("🔄 Training Advanced Ensemble Model...")

        # Scale features
        X_train_scaled = self.scaler.fit_transform(X_train)
        X_val_scaled = self.scaler.transform(X_val)

        # Train all models with scaled data
        self.rf_model.fit(X_train_scaled, y_train)
        self.xgb_model.fit(X_train_scaled, y_train)
        self.lgb_model.fit(X_train_scaled, y_train)
        self.gb_model.fit(X_train_scaled, y_train)

        # Calculate individual performance
        models = {
            'Random Forest': self.rf_model,
            'XGBoost': self.xgb_model,
            'LightGBM': self.lgb_model,
            'Gradient Boosting': self.gb_model
        }

        for name, model in models.items():
            train_acc = model.score(X_train_scaled, y_train)
            val_acc = model.score(X_val_scaled, y_val)
            print(f"📊 {name:16} - Train: {train_acc:.4f}, Val: {val_acc:.4f}")

        self.is_trained = True
        return True

    def predict(self, X):
        if not self.is_trained:
            raise ValueError("Model not trained!")

        # Scale input
        X_scaled = self.scaler.transform(X)

        # Get predictions from all models
        rf_pred = self.rf_model.predict(X_scaled)
        xgb_pred = self.xgb_model.predict(X_scaled)
        lgb_pred = self.lgb_model.predict(X_scaled)
        gb_pred = self.gb_model.predict(X_scaled)

        # Ensemble: if at least 2 models predict phishing, mark as phishing (lowering threshold for safety)
        ensemble_pred = np.where((rf_pred + xgb_pred + lgb_pred + gb_pred) >= 2, 1, 0)
        return ensemble_pred

    def predict_proba(self, X):
        if not self.is_trained:
            raise ValueError("Model not trained!")

        # Scale input
        X_scaled = self.scaler.transform(X)

        # Average probabilities from all models
        rf_proba = self.rf_model.predict_proba(X_scaled)[:, 1]
        xgb_proba = self.xgb_model.predict_proba(X_scaled)[:, 1]
        lgb_proba = self.lgb_model.predict_proba(X_scaled)[:, 1]
        gb_proba = self.gb_model.predict_proba(X_scaled)[:, 1]

        ensemble_proba = (rf_proba + xgb_proba + lgb_proba + gb_proba) / 4
        return ensemble_proba

