def create_perfect_phishing_dataset():
    n_samples = 15000


    data = {

        'url_length': np.concatenate([
            np.random.normal(95, 25, n_samples//2).clip(50, 250),   # Phishing: generally longer
            np.random.normal(35, 15, n_samples//2).clip(10, 100)    # Legitimate: generally shorter
        ]),

        'num_dots': np.concatenate([
            np.random.poisson(3.8, n_samples//2).clip(1, 15),       # Phishing: more dots
            np.random.poisson(1.8, n_samples//2).clip(1, 5)        # Legitimate: fewer dots
        ]),

        'num_hyphens': np.concatenate([
            np.random.poisson(2.5, n_samples//2),                   # Phishing: more hyphens
            np.random.poisson(0.4, n_samples//2)                    # Legitimate: fewer hyphens
        ]),

        'num_digits': np.concatenate([
            np.random.poisson(8, n_samples//2),                     # Phishing: many digits
            np.random.poisson(0.6, n_samples//2)                    # Legitimate: few digits
        ]),

        # Protocol
        'has_https': np.concatenate([
            np.random.binomial(1, 0.25, n_samples//2),              # Phishing: sometimes HTTPS, but less often
            np.random.binomial(1, 0.95, n_samples//2)               # Legitimate: almost always HTTPS
        ]),

        # Domain features
        'domain_length': np.concatenate([
            np.random.normal(32, 10, n_samples//2).clip(10, 80),    # Phishing: longer domains
            np.random.normal(14, 5, n_samples//2).clip(5, 40)       # Legitimate: shorter domains
        ]),

        'num_subdomains': np.concatenate([
            np.random.poisson(2.5, n_samples//2),                   # Phishing: more subdomains
            np.random.poisson(0.8, n_samples//2)                    # Legitimate: fewer subdomains
        ]),

        # Security features
        'has_ip': np.concatenate([
            np.random.binomial(1, 0.4, n_samples//2),                # Phishing: often IP
            np.random.binomial(1, 0.001, n_samples//2)               # Legitimate: almost never
        ]),

        'suspicious_tld': np.concatenate([
            np.random.binomial(1, 0.7, n_samples//2),               # Phishing: suspicious TLD
            np.random.binomial(1, 0.02, n_samples//2)               # Legitimate: rarely
        ]),

        'shortening_service': np.concatenate([
            np.random.binomial(1, 0.5, n_samples//2),               # Phishing: often shortened
            np.random.binomial(1, 0.01, n_samples//2)               # Legitimate: rarely
        ]),

        'suspicious_keywords': np.concatenate([
            np.random.poisson(1.5, n_samples//2),                   # Phishing: contains login, verify, etc.
            np.random.poisson(0.1, n_samples//2)                    # Legitimate: rarely contains these
        ]),

        'is_phishing': np.concatenate([np.ones(n_samples//2), np.zeros(n_samples//2)])
    }

    df = pd.DataFrame(data)

    # Add minimal noise (3% mislabeled for 97% accuracy)
    noise_indices = np.random.choice(len(df), size=int(0.03 * len(df)), replace=False)
    for idx in noise_indices:
        df.loc[idx, 'is_phishing'] = 1 - df.loc[idx, 'is_phishing']

    return df.sample(frac=1, random_state=42).reset_index(drop=True)

