def smart_feature_extraction(url):
    """Smart feature extraction that captures phishing patterns"""
    features = {}

    # Ensure URL has protocol
    if not url.startswith(('http://', 'https://')):
        url = 'http://' + url

    # Basic URL features
    features['url_length'] = len(url)
    features['num_dots'] = url.count('.')
    features['num_hyphens'] = url.count('-')
    features['num_digits'] = sum(c.isdigit() for c in url)
    features['has_https'] = 1 if url.startswith('https') else 0

    try:
        parsed = urlparse(url)
        domain = parsed.netloc

        # Domain features
        features['domain_length'] = len(domain)
        features['num_subdomains'] = domain.count('.')

        # TLD extraction
        ext = tldextract.extract(url)

        # Smart TLD detection - focus on uncommon TLDs
        common_tlds = ['com', 'org', 'net', 'edu', 'gov', 'io', 'co', 'ai']
        features['suspicious_tld'] = 1 if ext.suffix not in common_tlds else 0

        # IP address detection
        features['has_ip'] = 1 if re.match(r'^\d+\.\d+\.\d+\.\d+$', domain) else 0

        # Shortening service pattern
        short_patterns = ['.ly', '.gl', 'tinyurl', 'bit.ly', 'goo.gl', 't.co', 'ow.ly']
        features['shortening_service'] = 1 if any(pattern in domain for pattern in short_patterns) else 0

        # Phishing keyword patterns - Check ENTIRE URL
        phishing_keywords = ['login', 'verify', 'secure', 'account', 'banking', 'update',
                           'signin', 'confirm', 'password', 'wallet', 'payment', 'authenticate',
                           'validation', 'security', 'online', 'webscr', 'profile', 'ebayisapi',
                           'click', 'here', 'free', 'gift', 'award', 'claim', 'service']
        features['suspicious_keywords'] = sum(1 for word in phishing_keywords if word in url.lower())

        # Structural patterns
        features['has_dash_in_domain'] = 1 if '-' in domain else 0
        features['multiple_subdomains'] = 1 if features['num_subdomains'] >= 2 else 0
        features['long_url'] = 1 if features['url_length'] > 75 else 0
        features['long_domain'] = 1 if features['domain_length'] > 25 else 0

        # Entropy (randomness measure)
        if len(url) > 0:
            prob = [url.count(c) / len(url) for c in set(url)]
            features['entropy'] = -sum(p * np.log2(p) for p in prob)
        else:
            features['entropy'] = 0

    except Exception as e:
        # Default safe values
        features.update({
            'domain_length': 0, 'num_subdomains': 0, 'suspicious_tld': 0,
            'has_ip': 0, 'shortening_service': 0, 'suspicious_keywords': 0,
            'has_dash_in_domain': 0, 'multiple_subdomains': 0,
            'long_url': 0, 'long_domain': 0, 'entropy': 0
        })

    return features

def predict_website(url, model, feature_names):
    """Predict if URL is phishing or legitimate"""
    features = smart_feature_extraction(url)

    # Create feature vector matching training features
    feature_vector = []
    for feature in feature_names:
        if feature in features:
            feature_vector.append(features[feature])
        else:
            feature_vector.append(0)  # Default value for missing features

    feature_vector = np.array(feature_vector).reshape(1, -1)

    # Use the model's internal prediction methods (which now handle scaling)
    prediction = model.predict(feature_vector)[0]
    probability = model.predict_proba(feature_vector)[0]

    return prediction, probability, features

